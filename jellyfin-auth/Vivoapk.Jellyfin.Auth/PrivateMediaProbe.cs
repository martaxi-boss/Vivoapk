using System.ComponentModel;
using System.Diagnostics;
using System.Globalization;
using System.Text.Json;
using System.Text.RegularExpressions;

namespace Jellyfin.Plugin.VivoapkMegaAuth;

/// <summary>Reads only typed, bounded stream metadata from an already
/// authorized, process-private media lease. The executable is selected by
/// the trusted host, never by an HTTP caller. No raw probe output or source
/// URL may be logged, persisted or returned to a client.</summary>
internal static class PrivateMediaProbe
{
    private static readonly Regex Route = new(
        @"\A/vivoapk/[0-9a-f]{48}/(?:file|index\.m3u8|stream\.ts|probe\.ts)\z", RegexOptions.CultureInvariant);
    private static readonly HashSet<string> VideoCodecs = new(StringComparer.Ordinal)
        { "h264", "hevc", "mpeg2video", "mpeg4", "av1", "vp8", "vp9" };
    private static readonly HashSet<string> AudioCodecs = new(StringComparer.Ordinal)
        { "aac", "mp2", "mp3", "ac3", "eac3", "opus", "flac", "vorbis", "pcm_s16le" };

    internal sealed record StreamInfo(int Index, bool Video, string Codec, int? Width, int? Height,
        float? FrameRate, int? Channels, int? SampleRate, int? Bitrate,
        string? Profile = null, int? Level = null);
    internal sealed record AncillaryStreamInfo(int Index, string Codec);
    internal sealed record Observation(string Container, long? DurationTicks,
        int? Bitrate, IReadOnlyList<StreamInfo> Streams,
        IReadOnlyList<AncillaryStreamInfo>? AncillaryStreams = null);

    private static InvalidOperationException Unavailable()
        => new("Private media metadata unavailable");

    // Explicit raw TS input for a trusted host's already-admitted local lease.
    // No source resolution, provider request, fallback or public route here.
    internal static Task<Observation> ReadContinuousTsAsync(string executable, Uri source,
        CancellationToken ct)
        => ReadAsync(executable, source, finite: false, ct: ct, continuousTs: true);

    internal static async Task<Observation> ReadAsync(string executable, Uri source,
        bool finite, CancellationToken ct, bool continuousTs = false)
    {
        // Only the exact loopback capability generated by our bridge, with
        // no arbitrary paths, credentials, fragments or query strings.
        if ((finite && continuousTs) || !Path.IsPathFullyQualified(executable)
            || Path.GetFileName(executable) != "ffprobe"
            || !File.Exists(executable) || !source.IsAbsoluteUri || source.Scheme != "http"
            || source.Host != "127.0.0.1" || source.Port < 1024
            || source.UserInfo.Length != 0 || source.Query.Length != 0 || source.Fragment.Length != 0
            || !Route.IsMatch(source.AbsolutePath)
            || !(continuousTs
                ? source.AbsolutePath.EndsWith("/stream.ts", StringComparison.Ordinal)
                    || source.AbsolutePath.EndsWith("/probe.ts", StringComparison.Ordinal)
                : source.AbsolutePath.EndsWith(finite ? "/file" : "/index.m3u8",
                    StringComparison.Ordinal)))
            throw Unavailable();
        using var deadline = CancellationTokenSource.CreateLinkedTokenSource(ct);
        // A finite HTTP window is validated in full before its first byte is
        // delivered. The backend bounds one such operation at 30 seconds;
        // probing a non-fast-start file may also seek to its tail. Keep the
        // live probe budget unchanged and bound the finite operation separately.
        deadline.CancelAfter(TimeSpan.FromSeconds(finite ? 75 : 20));
        var token = deadline.Token;
        var start = new ProcessStartInfo(executable)
        {
            UseShellExecute = false, RedirectStandardOutput = true,
            RedirectStandardError = true, RedirectStandardInput = true,
            CreateNoWindow = true,
        };
        // No inherited proxies, FFREPORT, or other caller-controlled process
        // configuration. The official portable binary uses its own libraries.
        start.Environment.Clear();
        start.Environment["LC_ALL"] = "C";
        // The trusted caller selects exactly one admitted input contract.
        // Raw live TS is not a fallback for a refused HLS request.
        // No file or external protocol.
        foreach (var arg in new[] {
            "-hide_banner", "-v", "error", "-protocol_whitelist", "http,tcp",
            "-format_whitelist", finite ? "mov,mp4,m4a,3gp,3g2,mj2" : continuousTs ? "mpegts" : "hls,mpegts",
            "-rw_timeout", finite ? "35000000" : "8000000", "-probesize", "2097152",
            "-analyzeduration", "5000000", "-max_alloc", "67108864",
            "-f", finite ? "mov" : continuousTs ? "mpegts" : "hls",
            "-show_entries", "format=format_name,duration,bit_rate:stream=index,codec_type,codec_name,width,height,avg_frame_rate,channels,sample_rate,bit_rate",
            "-of", "json" })
            start.ArgumentList.Add(arg);
        if (continuousTs)
        {
            // A short TS sample normally has no format/video bit_rate. Counting
            // its actual encoded packets avoids reporting just the audio rate
            // as the whole channel, which made automatic quality choose 234p.
            // The same parser also supports an actual endless TS source.
            // Bound packet enumeration by media time, not process cancellation.
            start.ArgumentList.Add("-read_intervals");
            start.ArgumentList.Add("%+1");
            start.ArgumentList.Add("-show_packets");
            start.ArgumentList.Add("-show_entries");
            start.ArgumentList.Add("format=format_name,duration,bit_rate:stream=index,codec_type,codec_name,width,height,avg_frame_rate,channels,sample_rate,bit_rate,profile,level:packet=stream_index,size,pts_time,duration_time");
        }
        start.ArgumentList.Add(source.AbsoluteUri);
        Process? process = null;
        try
        {
            token.ThrowIfCancellationRequested();
            process = Process.Start(start) ?? throw Unavailable();
            process.StandardInput.Close();
            var output = ReadBoundedAsync(process.StandardOutput.BaseStream, continuousTs ? 1048576 : 65536, token);
            // Drain stderr with a separate cap, never include it in exceptions.
            var diagnostic = ReadBoundedAsync(process.StandardError.BaseStream, 65536, token);
            await Task.WhenAll(output, diagnostic, process.WaitForExitAsync(token)).ConfigureAwait(false);
            if (process.ExitCode != 0)
                throw Unavailable();
            return Parse(await output.ConfigureAwait(false), finite, continuousTs);
        }
        catch (Exception ex) when (ex is InvalidOperationException or IOException or Win32Exception
            or OperationCanceledException or JsonException or FormatException or OverflowException)
        {
            throw Unavailable();
        }
        finally
        {
            if (process is not null)
            {
                try
                {
                    if (!process.HasExited)
                    {
                        process.Kill(entireProcessTree: true);
                        using var stopped = new CancellationTokenSource(TimeSpan.FromSeconds(3));
                        await process.WaitForExitAsync(stopped.Token).ConfigureAwait(false);
                    }
                }
                finally { process.Dispose(); }
            }
        }
    }

    private static async Task<byte[]> ReadBoundedAsync(System.IO.Stream input, int cap, CancellationToken ct)
    {
        using var output = new MemoryStream();
        var buffer = new byte[8192];
        while (true)
        {
            int count = await input.ReadAsync(buffer.AsMemory(), ct).ConfigureAwait(false);
            if (count == 0)
                return output.ToArray();
            if (output.Length + count > cap)
                throw Unavailable();
            output.Write(buffer, 0, count);
        }
    }

    private static string? Value(JsonElement obj, string key)
    {
        if (!obj.TryGetProperty(key, out var v))
            return null;
        return v.ValueKind == JsonValueKind.String ? v.GetString()
            : v.ValueKind == JsonValueKind.Number ? v.GetRawText() : null;
    }

    private static int? IntValue(JsonElement obj, string key, int min, int max)
    {
        string? value = Value(obj, key);
        if (string.IsNullOrEmpty(value) || value == "N/A")
            return null;
        if (!int.TryParse(value, NumberStyles.None, CultureInfo.InvariantCulture, out int result)
            || result < min || result > max)
            throw Unavailable();
        return result;
    }

    private static float? FrameRate(JsonElement stream)
    {
        var value = Value(stream, "avg_frame_rate");
        if (value is null or "N/A" or "0/0" or "0/1")
            return null;
        var parts = value.Split('/');
        if (parts.Length != 2
            || !int.TryParse(parts[0], NumberStyles.None, CultureInfo.InvariantCulture, out int a)
            || !int.TryParse(parts[1], NumberStyles.None, CultureInfo.InvariantCulture, out int b)
            || a <= 0 || b <= 0 || (double)a / b > 240)
            throw Unavailable();
        return (float)a / b;
    }

    private static Dictionary<int, int> PacketBitrates(JsonElement root)
    {
        var rates = new Dictionary<int, int>();
        if (!root.TryGetProperty("packets", out var packets))
            return rates;
        if (packets.ValueKind != JsonValueKind.Array || packets.GetArrayLength() > 4096)
            throw Unavailable();
        var tracks = new Dictionary<int, (long Bytes, decimal Start, decimal End, int Count)>();
        foreach (var packet in packets.EnumerateArray())
        {
            var index = IntValue(packet, "stream_index", 0, 1024);
            var size = IntValue(packet, "size", 1, 16777216);
            if (index is null || size is null || !decimal.TryParse(Value(packet, "pts_time"),
                    NumberStyles.AllowLeadingSign | NumberStyles.AllowDecimalPoint,
                    CultureInfo.InvariantCulture, out var pts) || Math.Abs(pts) > 10000000)
                continue;
            decimal.TryParse(Value(packet, "duration_time"), NumberStyles.AllowDecimalPoint,
                CultureInfo.InvariantCulture, out var duration);
            if (duration < 0 || duration > 1)
                continue;
            var end = pts + duration;
            if (tracks.TryGetValue(index.Value, out var track))
                tracks[index.Value] = (track.Bytes + size.Value, Math.Min(track.Start, pts),
                    Math.Max(track.End, end), track.Count + 1);
            else
                tracks[index.Value] = (size.Value, pts, end, 1);
        }
        foreach (var (index, track) in tracks)
        {
            var span = track.End - track.Start;
            if (track.Count < 3 || span < .04m || span > 20)
                continue;
            var rate = track.Bytes * 8m / span;
            if (rate >= 1 && rate <= 500000000)
                rates[index] = decimal.ToInt32(decimal.Round(rate));
        }
        return rates;
    }

    internal static Observation Parse(byte[] bytes, bool finite, bool continuousTs = false)
    {
        if ((finite && continuousTs) || bytes.Length < 2 || bytes.Length > (continuousTs ? 1048576 : 65536))
            throw Unavailable();
        using var document = JsonDocument.Parse(bytes, new JsonDocumentOptions { MaxDepth = 12 });
        var root = document.RootElement;
        if (root.ValueKind != JsonValueKind.Object
            || !root.TryGetProperty("format", out var format) || format.ValueKind != JsonValueKind.Object
            || !root.TryGetProperty("streams", out var streams) || streams.ValueKind != JsonValueKind.Array
            || streams.GetArrayLength() is < 2 or > 9)
            throw Unavailable();
        string? name = Value(format, "format_name");
        if (name != (finite ? "mov,mp4,m4a,3gp,3g2,mj2" : continuousTs ? "mpegts" : "hls"))
            throw Unavailable();
        long? duration = null;
        var rawDuration = Value(format, "duration");
        // A probe window is not the duration of a continuous live channel.
        if (!continuousTs && rawDuration is not (null or "N/A"))
        {
            if (!double.TryParse(rawDuration, NumberStyles.AllowDecimalPoint,
                    CultureInfo.InvariantCulture, out double seconds)
                || !double.IsFinite(seconds) || seconds <= 0 || seconds > 30 * 86400)
                throw Unavailable();
            duration = TimeSpan.FromSeconds(seconds).Ticks;
        }
        if (finite && duration is null)
            throw Unavailable();

        var parsed = new List<StreamInfo>();
        var ancillary = new List<AncillaryStreamInfo>();
        var indices = new HashSet<int>();
        foreach (var stream in streams.EnumerateArray())
        {
            if (stream.ValueKind != JsonValueKind.Object)
                throw Unavailable();
            int index = IntValue(stream, "index", 0, 63) ?? throw Unavailable();
            string codec = Value(stream, "codec_name") ?? throw Unavailable();
            if (!indices.Add(index))
                throw Unavailable();
            int? bitrate = IntValue(stream, "bit_rate", 0, 500000000);
            switch (Value(stream, "codec_type"))
            {
                case "video" when VideoCodecs.Contains(codec):
                    parsed.Add(new StreamInfo(index, true, codec,
                        IntValue(stream, "width", 16, 8192) ?? throw Unavailable(),
                        IntValue(stream, "height", 16, 8192) ?? throw Unavailable(),
                        FrameRate(stream), null, null, bitrate));
                    break;
                case "audio" when AudioCodecs.Contains(codec):
                    parsed.Add(new StreamInfo(index, false, codec, null, null, null,
                        IntValue(stream, "channels", 1, 16) ?? throw Unavailable(),
                        IntValue(stream, "sample_rate", 8000, 192000) ?? throw Unavailable(), bitrate));
                    break;
                case "subtitle" when continuousTs && codec == "dvb_teletext":
                    // Observed on an authorized live TS alongside HEVC/AAC.
                    // Retain its typed identity separately. This private
                    // pipeline advertises and maps only video and audio;
                    // it does not promise teletext subtitle delivery.
                    ancillary.Add(new AncillaryStreamInfo(index, codec));
                    break;
                default:
                    // Every other extra track still needs explicit validation.
                    throw Unavailable();
            }
        }
        if (parsed.Count(s => s.Video) != 1 || !parsed.Any(s => !s.Video))
            throw Unavailable();
        if (continuousTs)
        {
            var measured = PacketBitrates(root);
            parsed = parsed.Select(track => measured.TryGetValue(track.Index, out var rate)
                ? track with { Bitrate = rate } : track).ToList();
        }
        parsed = parsed.Select(track =>
        {
            var observed = root.GetProperty("streams").EnumerateArray()
                .First(stream => IntValue(stream, "index", 0, 1024) == track.Index);
            var profile = Value(observed, "profile");
            if (profile is not null && (profile.Length > 64 || profile.Any(char.IsControl)))
                throw Unavailable();
            return track with { Profile = profile, Level = IntValue(observed, "level", 0, 1000) };
        }).ToList();
        int? total = IntValue(format, "bit_rate", 0, 500000000);
        if (continuousTs && parsed.Any(track => track.Video && track.Bitrate is > 0))
            total = checked(parsed.Sum(track => track.Bitrate ?? 0));
        return new Observation(finite ? "mp4" : "mpegts", duration,
            total, parsed.OrderBy(s => s.Index).ToArray(), ancillary.ToArray());
    }
}

